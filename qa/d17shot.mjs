// D17 の確かめ：交換所の CG集の棚・品を選んだ所・交換・コレクションの CG集・見る画面。node qa/d17shot.mjs [pc|phone|small]
import fs from 'node:fs';
import { openSession, sleep } from './lib/session.mjs';
const mode = process.argv[2] || 'pc';
const size = { pc: [1280, 800], phone: [844, 390], small: [667, 375] }[mode];
const OUT = `qa/out/d17/${mode}`; fs.mkdirSync(OUT, { recursive: true });
const session = await openSession({ width: size[0], height: size[1], mobile: mode !== 'pc', speed: 2 });
const { page } = session;
const ev = (js) => page.eval(`(() => { ${js}; return 1; })()`).catch(e => console.log('ERR', e.message.slice(0, 160)));
for (let i = 0; i < 60 && !(await page.eval('typeof render === "function" && typeof save === "object"').catch(() => false)); i++) await sleep(500);
const ALL = ['rico_tutorial', 'polka', 'selina', 'grano', 'velvet'];
await ev(`save.coins = 9000; save.introPlayed = true; save.clearedStages = ${JSON.stringify(ALL)}; save.rewardCgSeen = ${JSON.stringify(ALL)}; save.endingUnlocked = true; save.shopSeenItems = []; state.screen = 'shop'; shop3.group = 'cgset'; shop3.sel = null; render()`);
await sleep(mode === 'pc' ? 6000 : 4000);
let n = 0; const snap = async (name, w = 700) => { await sleep(w); n++; await page.screenshot(`${OUT}/${String(n).padStart(2, '0')}_${name}.png`); console.log(mode, name); };
await ev(`const c = [...document.querySelectorAll('.sh3-cats button, .sh3-cats [data-sh3-group], .sh3-cat')].find(b => b.textContent.includes('CG集')); if (c) c.click()`);
await snap('shelf', 1500);
await ev(`const c = document.querySelector('.sh3-card[data-sh3="cgset_bath"]'); if (c) c.click()`);
await snap('bath', 1500);
console.log(await page.eval(`(() => { const b = document.querySelector('.sh3-buy button, .sh3-buy [data-action]'); return b ? b.outerHTML.slice(0, 160) : 'no buy'; })()`));
await ev(`const b = document.querySelector('.sh3-buy [data-action="buy-item"], .sh3-buy button'); if (b) b.click()`);
await sleep(1500);
await ev(`const b = document.querySelector('.ui-confirm [data-ok], .confirm-ok, [data-action="confirm-ok"]'); if (b) b.click()`);
await snap('after_buy', 2500);
console.log('owned', await page.eval(`isItemOwned('cgset_bath')`));
await ev(`save.ownedItems = [...new Set([...(save.ownedItems||[]), 'cgset_bath', 'cgset_yshirt'])]; state.screen = 'lobby'; render(); showCollectionModal()`);
await sleep(2500);
await ev(`const e = [...document.querySelectorAll('.coll-section-title')].find(h => h.textContent.includes('CG集')); if (e) e.scrollIntoView({ block: 'start' })`);
await snap('coll_sets', 900);
await ev(`document.querySelector('.coll-cg-card.is-set.on').click()`);
await snap('viewer1', 1500);
await ev(`const o = document.querySelector('.reward-cg-viewer-overlay'); const r = o.getBoundingClientRect(); o.dispatchEvent(new MouseEvent('click', { bubbles: true, clientX: r.right - 50, clientY: r.top + r.height / 2 }))`);
await snap('viewer2', 1200);
console.log('hint', await page.eval(`document.querySelector('.reward-cg-viewer-hint').textContent`));
console.log('err', JSON.stringify(session.exceptions).slice(0, 400));
await session.close();
